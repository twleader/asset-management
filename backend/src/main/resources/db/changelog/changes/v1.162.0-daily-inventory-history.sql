CREATE TABLE IF NOT EXISTS daily_inventory_snapshot (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
  market VARCHAR(20) NOT NULL CHECK (market IN ('台股','美股')),
  trading_date DATE NOT NULL,
  session_close_at TIMESTAMPTZ NOT NULL,
  scheduled_at TIMESTAMPTZ NOT NULL,
  captured_at TIMESTAMPTZ NOT NULL,
  source_snapshot_id BIGINT NOT NULL,
  source_snapshot_date DATE NOT NULL,
  status VARCHAR(10) NOT NULL CHECK (status IN ('SAVED','EMPTY')),
  CONSTRAINT uq_daily_inventory_owner_market_date UNIQUE (owner_user_id,market,trading_date),
  CONSTRAINT ck_daily_inventory_schedule CHECK (scheduled_at=session_close_at+INTERVAL '6 hours'),
  CONSTRAINT ck_daily_inventory_capture CHECK (captured_at>=scheduled_at)
);
CREATE TABLE IF NOT EXISTS daily_inventory_position (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  snapshot_id BIGINT NOT NULL REFERENCES daily_inventory_snapshot(id),
  source_holding_id BIGINT NOT NULL,
  stock_code VARCHAR(20) NOT NULL,
  broker_id BIGINT REFERENCES broker(id),
  shares NUMERIC(15,5) NOT NULL CHECK (shares>=0),
  investment_cost NUMERIC(20,2) NOT NULL CHECK (investment_cost>=0),
  currency VARCHAR(3),
  transaction_exchange_rate NUMERIC(10,4),
  CONSTRAINT uq_daily_inventory_source_holding UNIQUE (snapshot_id,source_holding_id)
);
CREATE OR REPLACE FUNCTION reject_daily_inventory_mutation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'daily inventory history is immutable' USING ERRCODE='23514';
END;
$$;
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='daily_inventory_snapshot_immutable' AND tgrelid='daily_inventory_snapshot'::regclass) THEN
    CREATE TRIGGER daily_inventory_snapshot_immutable BEFORE UPDATE OR DELETE ON daily_inventory_snapshot
      FOR EACH ROW EXECUTE FUNCTION reject_daily_inventory_mutation();
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_trigger WHERE tgname='daily_inventory_position_immutable' AND tgrelid='daily_inventory_position'::regclass) THEN
    CREATE TRIGGER daily_inventory_position_immutable BEFORE UPDATE OR DELETE ON daily_inventory_position
      FOR EACH ROW EXECUTE FUNCTION reject_daily_inventory_mutation();
  END IF;
END $$;
