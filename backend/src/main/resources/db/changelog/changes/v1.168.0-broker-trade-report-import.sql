ALTER TABLE asset_transaction DROP CONSTRAINT IF EXISTS asset_transaction_source_check;
ALTER TABLE asset_transaction ADD CONSTRAINT asset_transaction_source_check CHECK (source IN ('MANUAL','FUBON_SYNC','FUBON_EMAIL'));
CREATE TABLE IF NOT EXISTS broker_trade_report_receipt (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
 source_message_id VARCHAR(200) NOT NULL,
 raw_sha256 VARCHAR(64) NOT NULL CHECK (raw_sha256 ~ '^[a-f0-9]{64}$'),
 parser_version VARCHAR(40) NOT NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(owner_user_id,source_message_id)
);
CREATE TABLE IF NOT EXISTS broker_trade_report_import (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
 parser_version VARCHAR(40) NOT NULL,
 identity_hash VARCHAR(64) NOT NULL CHECK (identity_hash ~ '^[a-f0-9]{64}$'),
 facts_hash VARCHAR(64) NOT NULL CHECK (facts_hash ~ '^[a-f0-9]{64}$'),
 canonical_facts TEXT NOT NULL,
 transaction_id BIGINT REFERENCES asset_transaction(id) ON DELETE SET NULL,
 created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
 UNIQUE(owner_user_id,identity_hash)
);
CREATE TABLE IF NOT EXISTS broker_trade_report_receipt_line (
 receipt_id BIGINT NOT NULL REFERENCES broker_trade_report_receipt(id),
 evidence_id BIGINT NOT NULL REFERENCES broker_trade_report_import(id),
 PRIMARY KEY(receipt_id,evidence_id)
);
-- Immutable provenance; only the FK's deletion tombstone may clear transaction_id.
CREATE OR REPLACE FUNCTION guard_broker_trade_report_evidence() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
 IF TG_OP = 'DELETE' THEN RAISE EXCEPTION 'REPORT_EVIDENCE_IMMUTABLE'; END IF;
 IF TG_TABLE_NAME = 'broker_trade_report_import' THEN
  IF NEW.transaction_id IS NULL AND OLD.transaction_id IS NOT NULL AND
    (to_jsonb(NEW)-'transaction_id') = (to_jsonb(OLD)-'transaction_id') THEN RETURN NEW; END IF;
 END IF;
 RAISE EXCEPTION 'REPORT_EVIDENCE_IMMUTABLE';
END $$;
CREATE OR REPLACE TRIGGER broker_trade_report_import_immutable BEFORE UPDATE OR DELETE ON broker_trade_report_import FOR EACH ROW EXECUTE FUNCTION guard_broker_trade_report_evidence();
CREATE OR REPLACE TRIGGER broker_trade_report_receipt_immutable BEFORE UPDATE OR DELETE ON broker_trade_report_receipt FOR EACH ROW EXECUTE FUNCTION guard_broker_trade_report_evidence();
CREATE OR REPLACE TRIGGER broker_trade_report_line_immutable BEFORE UPDATE OR DELETE ON broker_trade_report_receipt_line FOR EACH ROW EXECUTE FUNCTION guard_broker_trade_report_evidence();
