CREATE OR REPLACE FUNCTION reject_api_error_log_operation_mutation() RETURNS trigger AS $$
BEGIN RAISE EXCEPTION 'api_error_log_operation is immutable'; END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS api_error_log_operation_immutable ON api_error_log_operation;
CREATE TRIGGER api_error_log_operation_immutable
    BEFORE UPDATE OR DELETE ON api_error_log_operation
    FOR EACH ROW EXECUTE FUNCTION reject_api_error_log_operation_mutation();

CREATE OR REPLACE FUNCTION guard_api_error_log_retention() RETURNS trigger AS $$
BEGIN
    IF TG_OP = 'UPDATE' THEN RAISE EXCEPTION 'api_error_log is append-only'; END IF;
    IF OLD.occurred_at >= transaction_timestamp() - interval '30 days' THEN
        RAISE EXCEPTION 'api_error_log is within retention window';
    END IF;
    RETURN OLD;
END;
$$ LANGUAGE plpgsql;
DROP TRIGGER IF EXISTS api_error_log_retention_guard ON api_error_log;
CREATE TRIGGER api_error_log_retention_guard
    BEFORE UPDATE OR DELETE ON api_error_log
    FOR EACH ROW EXECUTE FUNCTION guard_api_error_log_retention();
