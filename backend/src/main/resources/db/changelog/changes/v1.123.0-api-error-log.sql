CREATE TABLE IF NOT EXISTS api_error_log_operation (
    source VARCHAR(16) NOT NULL CHECK (source IN ('OPEN_API', 'FUBON_API')),
    operation_key VARCHAR(160) NOT NULL,
    operation_label VARCHAR(255) NOT NULL,
    display_order SMALLINT NOT NULL CHECK (display_order > 0),
    PRIMARY KEY (source, operation_key),
    UNIQUE (source, operation_key, operation_label)
);

CREATE TABLE IF NOT EXISTS api_error_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(16) NOT NULL CHECK (source IN ('OPEN_API', 'FUBON_API')),
    operation_key VARCHAR(160) NOT NULL,
    api_name VARCHAR(255) NOT NULL,
    message_header TEXT NOT NULL,
    stack_trace TEXT NOT NULL,
    occurred_at TIMESTAMPTZ NOT NULL,
    FOREIGN KEY (source, operation_key, api_name)
        REFERENCES api_error_log_operation (source, operation_key, operation_label)
        ON UPDATE RESTRICT ON DELETE RESTRICT
);

CREATE INDEX IF NOT EXISTS idx_api_error_log_source_operation_time
    ON api_error_log (source, operation_key, occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_api_error_log_source_name_time
    ON api_error_log (source, api_name, occurred_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS idx_api_error_log_time ON api_error_log (occurred_at DESC, id DESC);

