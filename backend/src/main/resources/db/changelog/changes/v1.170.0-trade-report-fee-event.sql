-- The composite parent key makes an event referring to another owner's import impossible.
CREATE UNIQUE INDEX IF NOT EXISTS ux_trade_report_import_owner_evidence
 ON broker_trade_report_import(owner_user_id,id);
CREATE TABLE IF NOT EXISTS broker_trade_report_fee_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id BIGINT NOT NULL,
 import_evidence_id BIGINT NOT NULL,
 kind VARCHAR(20) NOT NULL CHECK (kind IN ('MANUAL_EDIT','FEE_ENRICHMENT')),
 payload_jcs TEXT NOT NULL CHECK (jsonb_typeof(payload_jcs::jsonb)='object'),
 created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (owner_user_id,import_evidence_id) REFERENCES broker_trade_report_import(owner_user_id,id)
);
CREATE UNIQUE INDEX IF NOT EXISTS ux_trade_report_fee_enrichment
 ON broker_trade_report_fee_event(import_evidence_id) WHERE kind='FEE_ENRICHMENT';
CREATE INDEX IF NOT EXISTS ix_trade_report_fee_event_owner_evidence_kind
 ON broker_trade_report_fee_event(owner_user_id,import_evidence_id,kind);
CREATE OR REPLACE FUNCTION guard_broker_trade_report_fee_event() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'TRADE_REPORT_FEE_EVENT_IMMUTABLE'; END $$;
CREATE OR REPLACE TRIGGER broker_trade_report_fee_event_immutable BEFORE UPDATE OR DELETE
 ON broker_trade_report_fee_event FOR EACH ROW EXECUTE FUNCTION guard_broker_trade_report_fee_event();
