CREATE TABLE IF NOT EXISTS fubon_settlement_receipt (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 owner_user_id BIGINT NOT NULL REFERENCES app_user(id),
 query_date DATE NOT NULL,
 observed_at TIMESTAMP WITH TIME ZONE NOT NULL,
 status VARCHAR(20) NOT NULL CHECK (status IN ('VERIFIED','UNAVAILABLE')),
 account_fingerprint VARCHAR(128),
 payload_hash VARCHAR(64) NOT NULL CHECK (payload_hash ~ '^[a-f0-9]{64}$'),
 payload_jcs TEXT NOT NULL,
 reason VARCHAR(80),
 CHECK ((status='VERIFIED' AND account_fingerprint IS NOT NULL AND reason IS NULL) OR status='UNAVAILABLE')
);
CREATE INDEX IF NOT EXISTS ix_fubon_settlement_receipt_owner_date_id ON fubon_settlement_receipt(owner_user_id,query_date,id DESC);
CREATE INDEX IF NOT EXISTS ix_fubon_settlement_receipt_owner_latest ON fubon_settlement_receipt(owner_user_id,id DESC);
CREATE OR REPLACE FUNCTION guard_fubon_settlement_receipt() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'SETTLEMENT_RECEIPT_IMMUTABLE'; END $$;
CREATE OR REPLACE TRIGGER fubon_settlement_receipt_immutable BEFORE UPDATE OR DELETE ON fubon_settlement_receipt FOR EACH ROW EXECUTE FUNCTION guard_fubon_settlement_receipt();
