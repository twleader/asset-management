CREATE TABLE IF NOT EXISTS exchange_rate_source_capture (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 provider VARCHAR(64) NOT NULL,
 rate_basis VARCHAR(32) NOT NULL CHECK (rate_basis='BANK_SPOT_SELLING'),
 source_url TEXT NOT NULL CHECK (source_url LIKE 'https://%' AND source_url !~* '(token|password|api_key|authorization)='),
 captured_at TIMESTAMPTZ NOT NULL,
 source_sha256 CHAR(64) NOT NULL CHECK (source_sha256 ~ '^[a-f0-9]{64}$'),
 raw_body TEXT NOT NULL,
 UNIQUE(provider,rate_basis,source_sha256,source_url,captured_at)
);
ALTER TABLE exchange_rate_history ADD COLUMN IF NOT EXISTS source_capture_id BIGINT REFERENCES exchange_rate_source_capture(id);
ALTER TABLE exchange_rate_history ADD COLUMN IF NOT EXISTS source_member_sha256 CHAR(64);
DO $$ BEGIN
 IF NOT EXISTS(SELECT 1 FROM pg_constraint WHERE conname='exchange_rate_history_source_pair') THEN
  ALTER TABLE exchange_rate_history ADD CONSTRAINT exchange_rate_history_source_pair CHECK (
   (source_capture_id IS NULL AND source_member_sha256 IS NULL) OR
   (source_capture_id IS NOT NULL AND source_member_sha256 IS NOT NULL AND source_member_sha256 ~ '^[a-f0-9]{64}$'));
 END IF;
END $$;
CREATE OR REPLACE FUNCTION immutable_exchange_rate_capture() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN RAISE EXCEPTION 'FX source captures are immutable' USING ERRCODE='23514'; END;
$$;
DROP TRIGGER IF EXISTS immutable_exchange_rate_capture_trigger ON exchange_rate_source_capture;
CREATE TRIGGER immutable_exchange_rate_capture_trigger BEFORE UPDATE OR DELETE ON exchange_rate_source_capture
 FOR EACH ROW EXECUTE FUNCTION immutable_exchange_rate_capture();
