    // ⚠ **守門詞絕對不可用 GEO_REGION／CHINA／POLITY_STRONG 這類「有沒有提到某個國家或政治角色」的
    // 集合**——體育本質上就是國際的，巴西／韓國／越南／中國 是體育報導的日常詞彙。對抗測試實證：用它們
    // 當守門時，「世界盃巴西隊球迷抵制主辦單位售票制度」「韓國職棒球星遭球團驅逐出隊」「中國羽球選手
    // 遭禁藥制裁」等 8 則一般體育新聞 8 則全部被誤救。同理 政府（「政府制裁禁藥球員」）與 總統
    // （子字串誤中「總統盃」全國羽球錦標賽——本專案 北市⊂竹北市、陽明⊂陽明交大 的同型陷阱）亦刻意排除。
    //
    // **只收人為攻擊與國家層級政治，不收意外災難**（使用者 2026-07-27 裁示：「看台倒塌 逾百人罹難」
    // 若非人為攻擊而是建築物太爛，影響不了國際政治／經濟／股市，這類不要）。故場館事故詞
    // （踩踏／倒塌／坍塌／暴動／騷亂）與傷亡數字守門一律不納入——它們指向工安與管理不善。
    private static final Set<String> SPORT_GEO = set("抵制", "杯葛", "制裁", "爆炸", "暗殺", "驅逐");
    private static final Set<String> SPORT_GEO_GUARD = set(
            "外交", "主權", "代表權", "國旗", "國歌", "多國", "聯合國",
            "反恐", "邦交", "斷交", "正名", "國安", "戰爭", "入侵");

    // FINANCE 白名單在「體育帶動之產業／贊助／關稅」報導上的已知召回缺口補丁（Task 241）。
    // **只在體育否決這一條當豁免用，不改動 FINANCE 本身**，避免與本任務無關的全域回歸。
    //   贊助商：moneydj「世界盃決賽Nike無緣亮相 adidas成贊助商大贏家」FINANCE 命中＝空，但屬必保
    //           （運動用品股報導）。全語料 贊助商 僅 1 則＝該則本身，爆炸半徑 1。
    //   加税  ：wantgoo「無物皆稅！FIFA世足冠軍賽…川普痛批並威脅要加税」——該則標題自身的錯字
    //           （前半正體「無物皆稅」、後半誤植簡體「加税」），FINANCE 的 加稅／關稅 因而漏接。
    //           全 DB 含「税」者僅此 1 列，另查 关税／股价／经济／营收 等 13 個常見簡體形皆 0 則，
    //           故為單則錯字補丁而非繁簡管道缺口。
    private static final Set<String> SPORT_ECON_EXEMPT = set("贊助商", "加税");

    private static final Set<String> LOTTERY = set(
            "統一發票", "中獎", "獎號", "兌獎", "刮刮樂", "幸運兒", "頭獎", "大樂透");

    // ===== 家事遺產糾紛（Task 240）：置於 FINANCE 之前 =====
    // 「很多家庭急著分遺產 忘了另一位父母還活著」這類家事／繼承糾紛軟文，對股市無資訊量。**標題單獨
    // 判定為 DROP:non-finance-general，是其摘要（「房子要不要賣？存款怎麼分？」）把它救回 KEEP:finance**
    // ——證明本規則必須凌駕 FINANCE，只把來源接上過濾並不足夠。
    //
    // 三類豁免（ESTATE_EXEMPT）使這些**不被本規則否決**（能否收錄仍由後續 cascade 決定，非保證 KEEP）：
    // 法制（「遺產可免分兄弟姊妹？立院朝野拍板 特留分修法7/28處理」）、稅制（「被繼承人遺有應收股利
    // 遺產稅申報一次看」「分產喬不攏代價大！千萬遺產稅晚繳一個月」）、市場主體（「台積電配息創新高、
    // 繼承股票先別high！國稅局爆『這天』成股利報稅分水嶺」）。
    //
    // 刻意排除（實測會誤殺，勿加入 ESTATE_TOPIC）：家產（誤中「國家產業園區」→ 打到「三星…龍仁半導體
    // 國家產業園區首座晶圓廠量產提前一年」）、分產／爭產（充分產能／部分產品／競爭產業 子字串風險，且
    // 該類標題已由 遺產 命中，冗餘）。
    // ESTATE_EXEMPT 刻意不收「集團」：語料中「集團」與「遺產／繼承」零共現、無證據支撐，而它是高頻泛詞
    // （詐騙集團／犯罪集團）且同時存在於 FINANCE，收了會讓「詐騙集團騙走老翁遺產」落回 KEEP:finance。
    private static final Set<String> ESTATE_TOPIC = set("遺產", "遺囑", "繼承人", "特留分");
    private static final Set<String> ESTATE_EXEMPT = set(
            "立院", "立法院", "修法", "法案", "三讀", "朝野", "釋憲", "大法官",
            "國稅局", "財政部", "申報", "稅制", "課稅", "遺產稅", "贈與稅", "節稅",
            "台積電", "股利", "配息", "除息", "董事長", "董座", "經營權", "接班");

    /** 過濾一批新聞，只留符合編輯政策者。 */
    public static List<NewsRow> retain(List<NewsRow> rows) {
        List<NewsRow> out = new ArrayList<>(rows.size());
        for (NewsRow r : rows) {
            if (keep(r)) out.add(r);
        }
        return out;
    }

    public static boolean keep(NewsRow r) {
        return trace(text(r)).startsWith("KEEP");
    }

    public static boolean keep(String title) {
        return trace(title).startsWith("KEEP");
    }

    private static String text(NewsRow r) {
        String t = r.title() == null ? "" : r.title();
        String s = r.summary() == null ? "" : r.summary();
        return s.isEmpty() ? t : t + " " + s;
    }

    /**
     * 回傳判定結果與原因，格式 {@code KEEP:<reason>} 或 {@code DROP:<reason>}，供單元測試與稽核。
     * cascade 第一個命中的規則決定結果。
     */
    public static String trace(String text) {
        String t = text == null ? "" : text;

        // 0) 財經軼事／都市傳說否決（Task 221）：**唯一凌駕 FINANCE 的規則**。個人理財軼事必帶財經詞，
        //    不先於財經判定就永遠攔不到；觸發需同時滿足「N歲」＋（身分稱謂｜釣魚詞），爆炸半徑為零。
        if (isAnecdote(t)) return "DROP:anecdote";

        // 0b) 發票／彩券中獎否決（Task 240）：此類必帶金額詞（千萬／加碼／億），不先於財經判定就永遠攔不到。
        if (isLottery(t)) return "DROP:lottery";

        // 0c) 家事遺產糾紛否決（Task 240）：標題雖多為非財經，但摘要常含「存款／房子」而在規則①被救回，
        //     故同樣必須凌駕 FINANCE；法制／稅制／市場主體三類由 ESTATE_EXEMPT 豁免。
        if (isFamilyEstate(t)) return "DROP:family-estate";

        // 1) 財經一律保留（涵蓋最廣）＝生活/軟文/體育/社會獵奇的唯一豁免（「影響股市大盤」）
        if (containsAny(t, FINANCE)) return "KEEP:finance";

        // 1b) 社會獵奇／犯罪獄政／榮典否決（Task 221）：緊接財經豁免之後、其他所有規則之前，
        //     才攔得到原本在規則4 被誤判為地緣政治的「以色列…鱷魚可部署監獄周邊」。
        if (containsAny(t, SOCIAL_ODDITY)) return "DROP:social-oddity";

        // 1c) 南海小型海上摩擦否決（Task 229）：南海地區詞＋低烈度摩擦詞＋未升級 → 濾。置於財經／社會獵奇
        //     之後、生活／中國之前，才攔得到原在規則③被 KEEP:china-regime 收錄的「南海海警持棍傷人」類雜訊。
        //     升級為真正衝突（開火／飛彈／封鎖…）者由 SCS_ESCALATION 守門救回、落回規則③以 KEEP:china-regime 收錄。
        if (isSouthChinaSeaSkirmish(t)) return "DROP:scs-skirmish";

        // 1d) 體育賽事否決（Task 241）：使用者需求「刪除所有體育賽事，除非發生影響國際政治的大新聞」。
        //     **必須置於規則①FINANCE 之後**（冠軍／奪冠／封王／電競／球員 大量是財經比喻，實測前移會誤殺 43 則）；
        //     **必須置於規則②LIFESTYLE 之前**：體育詞雖已移出 LIFESTYLE，但體育事件常同時命中**非體育**的
        //     LIFESTYLE 詞——實測「奧運開幕演唱會遭恐怖攻擊 多國元首緊急撤離」（演唱會）、「世界盃球迷粉絲
        //     見面會爆炸案 主辦國提升反恐」（粉絲），①d 在②後會被判 DROP:lifestyle。
        //     排在 ①b SOCIAL_ODDITY／①c SCS 之後是刻意的：讓「奧運選手越獄」仍由 SOCIAL_ODDITY 處理。
        String sport = traceSport(t);
        if (sport != null) return sport;

        // 2) 全世界生活／消費／娛樂／體育軟文否決——除非上方已判為財經，否則一律濾除；政治/中國/地緣/城市白名單皆不救回
        if (containsAny(t, LIFESTYLE)) return "DROP:lifestyle";

        // 3) 中國相關：財經（已判）／北京政權中央政治／美日台歐盟雙邊／與他國雙邊外交／台灣政黨對中 保留，
        //    其餘（純社會獵奇）濾除
        if (containsAny(t, CHINA)) {
            if (containsAny(t, BEIJING_REGIME) || containsAny(t, POLITY_STRONG)
                    || containsAny(t, TW_POLITICS_GENERIC) || containsAny(t, GEO_REGION)) return "KEEP:china-regime";
            return "DROP:china-nonfinance";
        }

        // 4) 影響市場的地緣政治（地區＋觸發詞）
        if (containsAny(t, GEO_REGION) && containsAny(t, GEO_TRIGGER)) return "KEEP:market-geopolitics";

        // 5) 美／日／台／歐盟 強政治訊號（覆蓋地方地理判定）
        if (containsAny(t, POLITY_STRONG)) return "KEEP:polity-strong";

        // 6) 台灣其他縣市地方新聞 或 地方層級公職（且無白名單縣市）＝濾除
        if ((containsAny(t, TW_OTHER_COUNTY) || containsAny(t, TW_LOCAL_OFFICE))
                && !containsAny(t, TW_WHITELIST_CITY)) return "DROP:tw-local-other-county";

        // 7) 台灣政黨／選舉等一般政治（已排除他縣市地方選舉）
        if (containsAny(t, TW_POLITICS_GENERIC)) return "KEEP:tw-politics";

        // 8) 台北／新北／高雄 地方新聞
        if (containsAny(t, TW_WHITELIST_CITY)) return "KEEP:tw-whitelist-city";

        // 9) 其餘：非財經、非指定政治／地方 一般新聞（社會等）＝濾除
        return "DROP:non-finance-general";
    }

    /**
     * 體育賽事否決判定（Task 241）。回傳 {@code null} ＝本規則不表態，交由 cascade 續行。
     *
     * <p>兩層豁免：強豁免（{@link #SPORT_TERROR}，語意鎖死，單獨命中即保留）與弱豁免
     * （{@link #SPORT_GEO} ∧ {@link #SPORT_GEO_GUARD}）。豁免採**正向 KEEP** 而非「跳過否決續行
     * cascade」——實測後者救不回來：「俄羅斯重返奧運舞台 國際奧委會暫時解除處罰」續行後 ②③⑤ 皆無命中、
     * ④ 的 GEO_TRIGGER 落空，最終仍是 DROP:non-finance-general。
     *
     * <p><b>FINANCE 閘門內建於本方法</b>，使 {@link #trace} 與 {@link #traceFinanceFeed} 共用同一份
     * 語意、不會漂移（在 trace() 中規則① 已先回傳，此處的 FINANCE 檢查恆為 false，屬刻意的冗餘防呆）。
     *
     * <p><b>順序約束</b>：{@code SPORT} 成員檢查必須最先、{@code DROP:sport} 必須最後；中間三步
     * （強豁免／弱豁免／財經閘門）的相對順序經實測**不影響收錄結果**（全語料 diff＝0，只影響 label）。
     */
    private static String traceSport(String t) {
        if (!containsAny(t, SPORT)) return null;
        if (containsAny(t, SPORT_TERROR)) return "KEEP:sport-intl-politics";
        if (containsAny(t, SPORT_GEO) && containsAny(t, SPORT_GEO_GUARD)) return "KEEP:sport-intl-politics";
        if (containsAny(t, FINANCE) || containsAny(t, SPORT_ECON_EXEMPT)) return null;
        return "DROP:sport";
    }

    /** 發票／彩券中獎判定（Task 240）：命中專名，或「發票」與「開出」同時出現。 */
    private static boolean isLottery(String t) {
        return containsAny(t, LOTTERY) || (t.contains("發票") && t.contains("開出"));
    }

    /** 家事遺產糾紛判定（Task 240）：主題詞命中且未命中法制／稅制／市場主體豁免詞。 */
    private static boolean isFamilyEstate(String t) {
        return containsAny(t, ESTATE_TOPIC) && !containsAny(t, ESTATE_EXEMPT);
    }

    /**
     * 純財經來源（wantgoo／MoneyDJ）專用過濾（Task 240）：只套「三條凌駕 FINANCE 的否決集」
     * （⓪ 財經軼事、⓪b 發票彩券、⓪c 家事遺產），其餘一律保留。
     */
    public static List<NewsRow> retainForFinanceFeed(List<NewsRow> rows) {
        List<NewsRow> out = new ArrayList<>(rows.size());
        for (NewsRow r : rows) {
            if (traceFinanceFeed(text(r)).startsWith("KEEP")) out.add(r);
        }
        return out;
    }

    /**
     * 純財經來源的判定（Task 240），格式同 {@link #trace}。**刻意只跑三條凌駕 FINANCE 的否決集**——
     * 這三條的語意是「即使帶財經詞也無投資資訊量」，與來源是否財經專屬無關，故可跨來源套用。
     *
     * <p><b>刻意不套 LIFESTYLE／SOCIAL_ODDITY，也不套規則③～⑨的白名單 KEEP 與 non-finance-general 兜底</b>：
     * FINANCE 是為「從一般新聞版面挑出財經」而設的白名單，純財經站的財經用語大量不在其中。對線上語料實測，
     * 若對 wantgoo 套整套 trace()，41 則遭濾者含「Waymo傳2028年後終止合作 Uber跌逾4%」「〈華德動能訪廠〉
     * 樂估日本電巴市占率上看3成」「基本工資調漲至3萬」等明確財經；即使保留 FINANCE 豁免而僅加套 LIFESTYLE，
     * 仍誤殺「雄獅東北亞賞楓行程銷售破5成」「《DJ在線》旅行社下半年團費趨穩」「諾和諾德怒告禮來」等消費／
     * 旅遊類股報導，SOCIAL_ODDITY 的「越獄」亦誤中 AI jailbreak（「Hugging Face遭沙盒『越獄』攻擊」）。
     *
     * <p><b>方法體內不含 FINANCE 判定</b>——兜底本就是 KEEP，加了多餘；更不可比照 {@link #trace} 把 FINANCE
     * 排在三條否決之前，那會讓「7-11開出千萬中獎發票」在純財經來源退回 KEEP:finance、本規則對其失效。
     *
     * <p><b>已知殘留（刻意接受）</b>：純財經來源的體育賽事軟文仍會入庫（語料約 4／1219：奧運處罰、世足 AI
     * 押注×2、川普出席世界盃決賽）。日後若要處理，正解是加一條**窄**的體育賽事否決集，而非改套整套 LIFESTYLE。
     */
    public static String traceFinanceFeed(String text) {
        String t = text == null ? "" : text;
        if (isAnecdote(t)) return "DROP:anecdote";
        if (isLottery(t)) return "DROP:lottery";
        if (isFamilyEstate(t)) return "DROP:family-estate";
        // 體育賽事否決（Task 241）：與 trace() 共用 traceSport()，FINANCE 閘門內建其中。
        // 這裡沒有規則①，故純財經來源的體育新聞全靠該閘門豁免真財經——無閘門實測 1223 則中 12 則命中
        // SPORT、其中 8 則是誤殺（FIFA 90億美元／江子翠交易量奪冠／adidas 贊助商／世足加持日本電視
        // 出貨量／iPhone 17霸榜／川普加拿大關稅／加税FIFA／記憶體價格暴漲）。加上閘門後這些全部回到 KEEP。
        String sport = traceSport(t);
        if (sport != null) return sport;
        return "KEEP:finance-feed";
    }

    /** 財經軼事／都市傳說判定（Task 221）：需同時命中「N歲」與（身分稱謂｜釣魚詞）。 */
    private static boolean isAnecdote(String t) {
        if (!AGE.matcher(t).find()) return false;
        return containsAny(t, ANECDOTE_ROLE) || containsAny(t, ANECDOTE_BAIT);
    }

    /**
     * 南海小型海上摩擦判定（Task 229）：南海地區詞 ∧ 低烈度摩擦詞 ∧ ¬重大升級詞，三者皆成立才為真。
     * 南海地區詞須先剝除「中南海」（＝中共領導層駐地，與 South China Sea 無關）再比對「南海」子字串。
     */
    private static boolean isSouthChinaSeaSkirmish(String t) {
        boolean scsRegion = t.replace("中南海", "").contains("南海") || containsAny(t, SCS_FEATURE);
        return scsRegion
                && containsAny(t, SCS_SKIRMISH)
                && !containsAny(t, SCS_ESCALATION);
    }

    private static boolean containsAny(String text, Set<String> tokens) {
        for (String k : tokens) {
            if (text.contains(k)) return true;
        }
        return false;
    }
